#!/usr/bin/env python3
"""Convert the reMarkable SVGs the app uses into Android vector drawables (app/src/main/res/drawable/rm_<name>.xml).

The icons are single-colour <path d=... fill=... [fill-rule=evenodd]> files on a 48x48 grid, which map 1:1 to a
VectorDrawable. Anything else (groups, clip paths, rects) makes the script stop rather than guess.

Usage: python3 tools/svg_to_vector.py
"""
import os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "reference/remarkable-3.27.1.0/icons")
DST = os.path.join(ROOT, "app/src/main/res/drawable")

# Icons used by app/src/main/kotlin/app/inkbridge/ui/InkIcons.kt
USED = [
    "ballpoint", "fineliner", "marker", "pencil", "mechanical_pencil", "paintbrush", "calligraphy_pen",
    "highlighter", "shader", "eraser", "undo", "redo", "page_overview", "toolbar_hide", "dots_three_vertical",
    "lens", "plus", "x_medium", "stroke_thin", "stroke_medium", "stroke_thick",
]

def convert(name):
    s = open(os.path.join(SRC, name + ".svg"), encoding="utf8").read()
    if re.search(r"<(g|rect|circle|ellipse|clipPath|defs|line|polygon|polyline)\b", s):
        sys.exit(f"{name}: unsupported element")
    vb = re.search(r'viewBox="0 0 (\d+) (\d+)"', s)
    w, h = vb.groups()
    paths = re.findall(r"<path\b([^>]*)/>", s)
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- reMarkable 3.27.1.0 icon '{name}'; generated by tools/svg_to_vector.py -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{w}dp" android:height="{h}dp"',
        f'    android:viewportWidth="{w}" android:viewportHeight="{h}">',
    ]
    for attrs in paths:
        d = re.search(r'\sd="([^"]+)"', " " + attrs).group(1)
        even = 'fill-rule="evenodd"' in attrs
        out.append(f'    <path android:fillColor="#FF000000"{" android:fillType=\"evenOdd\"" if even else ""}')
        out.append(f'        android:pathData="{d}" />')
    out.append("</vector>")
    open(os.path.join(DST, f"rm_{name}.xml"), "w").write("\n".join(out) + "\n")

os.makedirs(DST, exist_ok=True)
for n in USED: convert(n)
print(f"wrote {len(USED)} drawables to {os.path.normpath(DST)}")
